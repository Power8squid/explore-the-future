<h2 id="section1">Frågeställning </h2>

<p><span lang=SV>Ledarskap, vad innebär det egentligen? Vilka
egenskaper är det som skapar en bra ledare? Vad är syftet med en ledare? Varför
behövs det en? Hur mäter man en bra ledare? Vad blir konsekvensen av dåligt
eller bristande (mediokert) ledarskap? Vilka ledningssystem eller metoder
behöver användas för att skapa en framgångsrik organisation? Hur stor betydelse
har en företagskultur?  Det är många frågor som alla är relevanta. Dessa har vi
frågat oss samt diskuterat kring för att få en bättre förståelse kring
ledarskap och vad vi alla eventuellt kan göra för att höja nivån på ledarskap.</span></p>

<h2 id="section2">Vad är syftet med att ha en ledare?</h2>

<p><span lang=SV>Ett typisk Wikipedia svar skulle vara något i denna
stil. Syftet med en bra ledare är att inspirera och vägleda sitt team mot
gemensamma mål på ett effektivt sätt. En bra ledare skapar en positiv
arbetsmiljö där medarbetare känner sig värdefulla, motiverade och engagerade.
Genom att utnyttja teamets samlade styrkor och främja samarbete bidrar ledaren
till organisationens övergripande framgång och utveckling. Låter kanske enkelt
nog, men det är när vi gräver djupare som vi får de svar som kommer ge oss
större förståelse. </span></p>

<h2 id="section3">Hur mäter man en bra ledare?</h2>

<p><span lang=SV>Att mäta saker är inte enkelt när det inte
finns tydliga data. När det gäller ledarskap så är det svårt att få direkta
svar. En delanledning är att initiativ och satsningar ibland tar flera år innan
man får någon tydlig bild på vilka resultat det har gett. Det gör det svårt att
bedöma om en ledare presterar bra eller inte. Sedan så finns det inga resultat
att jämföra med, vi kommer aldrig att veta vad resultatet hade varit med en
annan ledare i stället.</span></p>

<p><span lang=SV>Du kommer förmodligen inte märka om ett team under
en längre period ger ett minskat resultat på 15–20%. Eftersom ingen
organisation är statisk och saker förändras så kommer minskningen på resultat
att kunna kamoufleras med orsaker som högre arbetsbelastning eller ändrad
organisation och arbetsuppgifter för gruppen. Tappet i effektivitet kommer
förmodligen i stället kompenseras med förstärkning i teamet. Desto större team
desto mer kan det kamoufleras. Det är ännu svårare att mätas om teamet är
nybildat och det inte finns tydliga benchmark om vad som kan förväntas. </span></p>

<p><span lang=SV>Beroende på verkningsgraden i nuläget, kan en
procentuell ökning i output med en högpresterande ledare åstadkommas. På samma
sätt som det första exemplet så kan det vara svårt att se. Det kanske bara
dröjde innan det blev rimligt med förstärkning till teamet. I mer statiska
situationer är det svårare att kamouflera förändringar, men det är också där
som det sannolikt också är en lägre verkningsgrad. </span></p>

<p><span lang=SV>Så vilka tecken kan man då kolla på för att få
en förståelse för hur väl någon presterar i en ledarroll? Vi tror att man kan
göra det genom att ställa sig ett antal frågor i linje med vad en ledare ska
åstadkomma. Några tolkningar kring bedömningen av svaren; Finns inte svaren är
vi på en dålig nivå. Finns dem, men är enligt bästa praxis för den typen av
team är vi på en medelnivå. Om vi däremot vill ha extra bra ledare behöver svaren
innehålla egna slutsatser och idéer med underbyggda logiska argument som kan
ifrågasättas utan att dem faller sönder.</span></p>

<ul><li></span><span lang=SV>Vilka actions har ledaren tagit för att skapa en bättre
arbetsmiljö och varför leder dem till en bättre arbetsmiljö?</span></li>

<li></span><span lang=SV>På vilka sätt inspirerar ledaren till en högre prestation
och arbetsmoral?</span></li>

<li></span><span lang=SV>Vilka hinder för effektivt arbete har ledaren röjt
undan?</span></li>

<li></span><span lang=SV>Hur stora delar av arbetet läggs på att göra
arbetet bättre och/eller effektivare i framtiden? Vilka resultat kommer det att
ge framåt?</span></li>

<li></span><span lang=SV>Hur hanterar ledaren medarbetares svagheter och
styrkor? Underprestation måste förmedlas tydligt och konstruktivt. Höga
prestationer måste erkännas och visas uppskattning för. </span></li>

<li></span><span lang=SV>Hur bidrar allt detta till organisationens
övergripande mål?</span></li>

</ul><h2 id="section4">Vad krävs för att vara en bra ledare?</h2>

<h3>Framtidsinställning  </h3>

<p><span lang=SV>Om man börjar från toppen på en organisation
så ser vi att det behövs ett tydligt syfte. Detta börjar med den som leder
organisationen. Våra erfarenheter pekar på att det finns en del olika typer av
ledarskap. Nedan är en hypotetisk matris som vi tycker beskriver ledares
framtidsutsikter. Detta gäller också för ledare längre ner i organisationen,
men blir mer eller mindre svårt beroende på hur toppen agerar. </span></p>

