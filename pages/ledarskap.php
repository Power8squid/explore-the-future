</ul><h2 id="section7">Hur kan vi påverka framtiden att ha bättre ledarskap?</h2>

<p><span lang=SV>Det första vi tänker på är att individuella
ledare och styrelser ställer högre krav på ledarskap. Men för att ställa högre
krav behöver man vara ganska specifik. Förhoppningsvis ger den övriga texten
lite mer stöd för att inspireras till att ställa högre krav. </span></p>

<p><b>Krav från fackföreningar:</b><span
lang=SV> En idé är att försöka få fackföreningar att ställa högre krav på
organisationer på att dem ska ha bra utbildade ledare. Ett av de vanligaste
klagomålen som medarbetare har är att dem har dåliga chefer. Det behöver
nödvändigtvis inte alltid vara sant, men vi tror att det är ett vanligt
förekommande. Detta är högst beroende av definitionen av ”dåliga”. Vi fångar förmodligen
både mediokra och dåliga i de anekdoterna om dåliga chefer. Det vi vill eftersträva
är bra och exceptionella ledare.  Vi ser ändå att fackföreningar kan spela en
roll i att förbättra detta. Vad vi kan se hjälper det inte med incitamenten
företag naturligt har. Så vet du någon som är ledare i en fackförening som
undrar vad dem ska göra för att rättfärdiga deras existens, så tipsa. Dem är
trots allt i en nedåtgående trend och behöver göra förändringar om dem själva
tror att dem har ett syfte i framtiden.</span></p>

<p><b>Hjälpmedel för rekrytering:</b><span
lang=SV> Att utveckla ett verktyg med specifika kriterier för att bedöma en
persons lämplighet i en ledarposition hade varit intressant. Det är sannolikt
att det redan finns bra struktur och verktyg för detta. Frågan är om det går
att förbättra. Det vi tycker borde läggas större vikt på är att man ska vara
linjerad och tro på företagets syfte. Att personen har viljan att prestera bra
i rollen. Andra kriterier att lägga stor vikt vid är förmågan att lära sig. Om
någon visar stor förmåga till att lära sig nya saker så är det sannolikt att
dem kommer klara av vad som helst (Alla dessa kriterier gäller samtliga
rekryteringar tror vi). Sedan behöver vi också lägga till innehållet från stycket
”vad krävs för att vara en bra ledare?”</span></p>

<h2 id="section8">Vilka risker finns det i förslagen? </h2>

<p><span lang=SV>Risken finns att man har en för stor ambition
på vilket ledarskap man vill ha. Det kan göra att man inte klarar av att fylla
de rollerna som behövs. Detta är sannolikt varför vi inte ser att det finns så
många bra eller exceptionella ledare. Det finns helt enkelt inte tillräckligt
många. Sammantaget så anser vi ändå att risken är större om man inte har en
tydlighet i sin höga ambition. Vi ser inte att det kan bli sämre för att man
har en högre ambition. Resultatet av att inte ha en högre ambition är en större
risk. </span></p>

<h2 id="section9">Vidare funderingar?</h2>

<p><span lang=SV>Om man inte kan uppnå denna höga nivå av
ledarskap som vi söker. Måste vi då låta organisationerna vara mediokra? Finns
det någon mellanväg? Elle går det att uppnå genom ett bra ledarskap från
toppen? De kan ägnas mycket mer tid åt att fundera på vägar att påverka så att
vi får mer bra ledare. Kanske finns det bra hjälpmedel till att bli en bättre
ledare likt det finns för att gå ner i vikt eller utveckla andra färdigheter? Det
finns säkert bra strukturer för att rekrytera bra och exceptionella ledare. Det
är något som borde undersökas vidare.</span></p>

