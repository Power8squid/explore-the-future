</ul><p>Negativa orsaker:</p>

<ul><li></span><b>Politik:</b><span lang=SV> I kontexten vi
diskuterar detta så är det givetvis negativt att regeringar inför program för
att minska födelsetalen. </span></li>

<li></span><b>Kultur:</b><span lang=SV> Kulturförändring
med fokus på karriär, individualism och livsstil ser vi som att det i sig är bra.
Men fokus på att skaffa barn och ha stora familjer har istället fått alldeles
