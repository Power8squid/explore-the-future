</ul><h2 id="section6">Hur ser trenderna ut framåt?</h2>

<p><span lang=SV>Födelsetalen har stadigt sjunkit globalt de
senaste decennierna, och denna minskning förväntas fortsätta. Befolkningsprognoser
visar att världens totala fertilitetstal (genomsnittligt antal barn per kvinna)
kommer sjunka ytterligare fram till mitten av detta århundrade. Urbanisering ser
inte ut att stanna av utan verkar fortsätta i liknande takt. Mer jämställd
tillgång utbildning kommer också fortsätta öka globalt. I urbaniserade miljöer
fortsätter också barnafödandet skjutas upp till senare i livet. Bostadstillgång
för unga i urban miljö verkar också fortsätta vara ett problem. Vi ser inget
som tyder på att dessa trender skulle vända.</span></p>

<h2 id="section7">Vad får de för konsekvenser på lång sikt?</h2>

<p><span lang=SV>Vi väljer att fokusera på dem övergripande
konsekvenserna som eventuellt inte har andra svar på utmaningen med lägre
födelsetal. Alltså de utmaningar som inte går att förklara med andra orsaker
annat än låga födelsetal. </span></p>

<p><span lang=SV>Åldrande befolkning är ett stort hot och är i
vissa delar av världen redan ett problem. När födelsetalen sjunker och
människor lever längre, kommer en större och större andel av befolkningen att
bestå av äldre människor. Detta leder till att befolkningspyramiden vänds upp
och ner, där den arbetande befolkningen minskar i förhållande till antalet
pensionärer. Av samma orsak ökar efterfrågan på sjukvård och äldreomsorg.</span></p>

<p><span lang=SV>Globala befolkningstillväxt bromsar in, även
om den globala befolkningen fortfarande växer, förväntas tillväxttakten avta
under 2000-talet. Världens befolkning tros nå sin topp runt 9,7 miljarder
människor år 2064, enligt vissa uppskattningar, innan den börjar minska senare
under seklet. Denna prognos har dessutom en historik över att konsekvent
justeras till en lägre topp och tidigare (På grund av att födelsetalen gått ner
i snabbare takt än förutspått).</span></p>

<p><span lang=SV>Det blir svårare att få en stabil befolkning desto
längre period vi har låga födelsetal, eftersom det blir färre och färre
personer i fertil ålder, som måste vända trenden förr eller senare.</span></p>

<p><span lang=SV>Ekonomiskt så riskerar vi att få en
nedåtgående spiral. På samma sätt som vår ekonomi bygger på tillväxt som föder
tillväxt så kan det bli svårt om vi tvingas in i nedgång som föder nedgång.
Detta är förstås beroende på vilka andra teknologiska framsteg mänskligheten kan
göra i stort.</span></p>

<h2 id="section8"><span lang=SV>Vad kan man göra för att påverka? Vilken kunskap och vilka argument
behövs för att vända trenden?</span></h2>

<p><span lang=SV>Nedan har vi spånat fram ett antal idéer som
eventuellt kan påverka valet av att skaffa barn eller fler barn. </span></p>

<h3>Kunskap</h3>

<p><b>Allmän kunskap:</b><span lang=SV> Kunskap
och medvetenhet om långsiktiga konsekvenser gör förmodligen att allmänheten är
mer öppna för att stödja politiska reformer som uppmuntrar till barnafödande. Biologiska
aspekter som fertilitet och ålder kan också göra att inte lika många skjuter
upp barnafödande med risken att bli ofrivilligt barnlösa. </span></p>

<p><b><span lang=SV>Kunskap om hur äldre föräldrar ser på sin
tid som föräldrar med barn hemma:</span></b><span lang=SV> Föräldrar med vuxna
barn anser generellt att det var en positiv och givande del av livet, trots de
utmaningar det innebar när barnen var små. Och att dem är glada över att de
valt att skaffa både barn och flera. </span></p>

<p><b>Barn som socialt och emotionellt stöd:</b><span
lang=SV> Att lyfta fram hur större familjer (fler än 2 barn) kan skapa ett rikt
nätverk av stöd, både för föräldrar och mellan syskon, kan vara en stark
motivationsfaktor. I tider av ekonomisk osäkerhet eller personliga svårigheter
kan en större familj fungera som ett viktigt socialt skyddsnät. Att vara
förälder skapar också ofta en mening och kärlek för föräldrarnas egen existens.</span></p>

<p><b>Moraliska orsaker. Ta det som utmaning:</b><span
lang=SV> Vad funkar bäst “carrot or the stick”? Vem ska supporta dig när du
blir gammal. Vem ska betala din pension? Du betalar dina föräldrars pension
genom arbete, vem ska betala din om du inte har skaffat några barn? För att
skaffa barn krävs antingen mod eller (/ och) naivitet. Anser du dig
psykologiskt stark, då kanske du kan bära ett större ansvar till att skapa
nästa generation. Bevisa det genom att ta det större ansvaret. För att
mänskligheten ska finnas så måste man skaffa barn, om du inte gör det lägger du
det ansvaret på någon annan. Moraliskt så måste man skaffa barn om man kan
(minimum 2).</span></p>

<h3>Kultur</h3>

<p><b><span lang=SV>Försöka ändra på kulturen och fira stora
familjer:</span></b><span lang=SV> Många upplever i samhällen där kulturella
normer om små familjer dominerar att det ses som lite konstigt att man väljer
att skaffa fler barn än 2 barn. Skapa sociala eller kulturella evenemang som
firar och erkänner stora familjer kan vara ett sätt. Detta kan inkludera
prisutdelningar, erkännanden av föräldrar som haft många barn, eller speciella
firanden som synliggör deras bidrag till samhället. </span></p>

<p><b>Marknadsföring:</b><span lang=SV>
Ett av de mest kraftfulla sätten att förändra attityder är genom media och
populärkultur. Genom att framställa stora familjer som något positivt och
eftersträvansvärt kan man påverka allmänhetens uppfattning. TV-program, filmer,
och reklam kan lyfta fram stora familjer som lyckliga, framgångsrika och
harmoniska.</span></p>

<h3>Politiska åtgärder</h3>

<p><b>Statliga erkännanden:</b><span
lang=SV> Regeringar och andra samhällsaktörer kan lansera kampanjer som främjar
föräldraskap och specifikt lyfter fram fördelarna med att ha många barn. Detta
kan göras genom annonser, evenemang och utbildningskampanjer som betonar hur
stora familjer bidrar till samhällsgemenskap, trygghet och framtidstro. I vissa
länder har regeringar redan infört utmärkelser för föräldrar med många barn,
som t.ex. &quot;moderskapshjältar&quot; i Ryssland och liknande utmärkelser i
andra länder. Att införa sådana statliga erkännanden kan bidra till att höja
statusen för stora familjer.</span></p>

<p><b>Förmåner för stora familjer:</b><span
lang=SV> Att införa ekonomiska och sociala fördelar för familjer med fler barn
kan inte bara minska de ekonomiska bördorna utan också höja deras status. Dessa
förmåner kan omfatta allt från subventionerat boende och billigare skolgång
till rabatter på familjeaktiviteter. Fler exempel är ekonomiska incitament som
exempelvis billigare barnomsorg och sjukvård, barnbidrag, föräldrapenning och
skattefördelar.</span></p>

